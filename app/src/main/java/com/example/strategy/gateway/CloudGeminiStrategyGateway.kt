package com.example.strategy.gateway

import android.util.Log
import com.example.strategy.model.StrategyRecommendation
import com.example.strategy.model.StrategyRequest
import com.example.strategy.model.StrategySource
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.Schema
import com.google.firebase.ai.type.generationConfig
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.TimeoutCancellationException
import kotlinx.coroutines.withTimeout
import org.json.JSONObject

class CloudGeminiStrategyGateway : IStrategyGateway {

    override val gatewayName: String = "Cloud Gemini 3.8 Flash Gateway"

    private val strategySchema by lazy {
        Schema.obj(
            properties = mapOf(
                "title" to Schema.string(description = "Concise tactical advice title"),
                "analysis" to Schema.string(description = "Detailed strategic assessment of the game situation"),
                "tacticalTips" to Schema.array(
                    items = Schema.string(),
                    description = "Key tactical bullets to achieve victory"
                ),
                "suggestedMacroName" to Schema.string(description = "Recommended action or macro name", nullable = true)
            )
        )
    }

    private val model by lazy {
        val config = generationConfig {
            responseMimeType = "application/json"
            responseSchema = strategySchema
        }
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = config
        )
    }

    override suspend fun generateStrategy(request: StrategyRequest): StrategyRecommendation {
        val prompt = buildString {
            appendLine("You are an expert mobile gaming tactician and AI gameplay analyst.")
            appendLine("Analyze the following real-time mobile game state:")
            appendLine("- Game Title: ${request.gameProfile.name}")
            appendLine("- Genre: ${request.activeGenre.displayName}")
            appendLine("- Current Scene: ${request.currentVision.scene.displayName}")
            appendLine("- Boss/Enemy HP Ratio: ${request.currentVision.healthPercentage?.let { "${(it * 100).toInt()}%" } ?: "Full / Not Applicable"}")
            appendLine("- Detected UI Elements: ${request.currentVision.boundingBoxes.joinToString { it.label }}")
            appendLine("- OCR Detected Text: ${request.currentVision.rawTextDump.take(300)}")
            appendLine("- User Objective: ${request.userGoal}")
            appendLine("Provide a high-level tactical game analysis and 3 specific bullet tips for maximum efficiency.")
        }

        return try {
            val response = withTimeout(30_000L) {
                model.generateContent(prompt)
            }

            val jsonString = response.text ?: throw IllegalStateException("Cloud Gemini returned empty response.")
            val json = JSONObject(jsonString)

            val title = json.optString("title", "Gemini Tactical Assessment")
            val analysis = json.optString("analysis", "Strategy generated by Gemini 3.8 Flash.")
            val tipsArray = json.optJSONArray("tacticalTips")
            val tips = if (tipsArray != null) {
                (0 until tipsArray.length()).map { tipsArray.getString(it) }
            } else {
                listOf("Optimize skill cooldowns", "Maintain defensive timing", "Focus highest value targets")
            }
            val macroName = if (json.has("suggestedMacroName")) json.optString("suggestedMacroName") else null

            StrategyRecommendation(
                title = title,
                analysis = analysis,
                tacticalTips = tips,
                suggestedMacroName = if (macroName.isNullOrBlank()) null else macroName,
                source = StrategySource.CLOUD_GEMINI,
                confidence = 0.96f
            )
        } catch (e: TimeoutCancellationException) {
            Log.w("CloudGeminiGateway", "Cloud AI generation timed out after 30s", e)
            throw e
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e("CloudGeminiGateway", "Cloud Gemini generation failed", e)
            throw e
        }
    }
}
