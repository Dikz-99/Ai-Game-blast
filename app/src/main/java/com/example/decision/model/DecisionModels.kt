package com.example.decision.model

import com.example.automation.model.ActionCommand
import com.example.automation.model.MacroSequence
import com.example.data.local.entity.GameProfile
import com.example.vision.model.DetectedGameScene
import com.example.vision.model.VisionResult

/**
 * Lifecycle state of the Decision Engine.
 */
enum class DecisionState(val label: String) {
    IDLE("Idle - Standby"),
    OBSERVING("Observing Frame"),
    EVALUATING("Evaluating Priority Rules"),
    DISPATCHING("Dispatching Action"),
    COOLDOWN("Safety Cooldown"),
    EMERGENCY_HALTED("Emergency Halted")
}

/**
 * Contextual state fed into the Decision Engine for reasoning.
 */
data class DecisionContext(
    val activeProfile: GameProfile?,
    val latestVision: VisionResult?,
    val consecutiveUnknownScenes: Int = 0,
    val lastActionTimestamp: Long = 0L,
    val isAutoPilotActive: Boolean = false
)

/**
 * Outcome generated by the Priority Rule Evaluator.
 */
data class DecisionProposal(
    val scene: DetectedGameScene,
    val action: ActionCommand? = null,
    val macro: MacroSequence? = null,
    val explanation: String,
    val confidence: Float,
    val rulePriority: Int // Higher number = higher execution urgency
)
